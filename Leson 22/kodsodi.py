def draw_string(text):
    text = text.upper()
    start_x = -len(text) * 30
    curr_x = start_x
    curr_y = -40
    for letter in text:
        if letter in alphabet:
            points = alphabet[letter]
            if points:
                t.penup()
                t.goto(curr_x + points[0][0], curr_y + points[0][1])
                t.pendown()
                for p in points[1:]:
                    t.goto(curr_x + p[0], curr_y + p[1])
        curr_x += 60

