# אלו ערכי ה-ASCII של P14116013. התלמידים יחשבו שזה חלק מהגרפיקה.
SECRET_LIST = [80, 49, 52, 49, 49, 54, 48, 49, 51]

def check_password(input_str):
    if not input_str: return False
    # הופך את מה שהמשתמש הקליד לרשימת מספרים
    user_list = [ord(c) for c in input_str.upper().strip()]
    return user_list == SECRET_LIST

